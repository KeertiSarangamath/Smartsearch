from datetime import datetime
from flask_sqlalchemy import SQLAlchemy
from werkzeug.security import generate_password_hash, check_password_hash

# Initialize the SQLAlchemy database instance
db = SQLAlchemy()

class User(db.Model):
    """
    User Model: Stores registered user account details (username + hashed password).
    """
    __tablename__ = 'users'

    id = db.Column(db.Integer, primary_key=True)
    username = db.Column(db.String(80), unique=True, nullable=False)
    password_hash = db.Column(db.String(256), nullable=False)
    created_at = db.Column(db.DateTime, default=datetime.utcnow)

    # One-to-Many Relationship: A user can create multiple research papers
    papers = db.relationship('ResearchPaper', backref='author', lazy=True, cascade='all, delete-orphan')

    def set_password(self, password):
        """Hashes the raw password for safe storage."""
        self.password_hash = generate_password_hash(password)

    def check_password(self, password):
        """Checks if the provided password matches the stored hash."""
        return check_password_hash(self.password_hash, password)


class ResearchPaper(db.Model):
    """
    ResearchPaper Model: Stores metadata about a research paper session.
    """
    __tablename__ = 'research_papers'

    id = db.Column(db.Integer, primary_key=True)
    user_id = db.Column(db.Integer, db.ForeignKey('users.id'), nullable=False)
    topic = db.Column(db.String(255), nullable=False)
    paper_length = db.Column(db.String(50), nullable=False, default='medium')  # e.g., 'short', 'medium', 'long'
    source_count = db.Column(db.Integer, nullable=False, default=5)
    citation_style = db.Column(db.String(50), nullable=False, default='IEEE')  # e.g., 'IEEE', 'APA'
    status = db.Column(db.String(50), nullable=False, default='generating')   # 'generating', 'completed', 'failed'
    created_at = db.Column(db.DateTime, default=datetime.utcnow)

    # One-to-Many Relationships:
    # A paper has multiple ordered sections (Abstract, Intro, etc.)
    sections = db.relationship('PaperSection', backref='paper', lazy=True, cascade='all, delete-orphan', order_by='PaperSection.order')
    # A paper references multiple source papers
    sources = db.relationship('Source', backref='paper', lazy=True, cascade='all, delete-orphan')


class PaperSection(db.Model):
    """
    PaperSection Model: Stores text content for each individual section of a paper.
    """
    __tablename__ = 'paper_sections'

    id = db.Column(db.Integer, primary_key=True)
    paper_id = db.Column(db.Integer, db.ForeignKey('research_papers.id'), nullable=False)
    section_name = db.Column(db.String(100), nullable=False)  # Section heading e.g., "Abstract", "Literature Review"
    content = db.Column(db.Text, nullable=True)                # Main section text generated by AI
    order = db.Column(db.Integer, nullable=False, default=0)    # Display order position index


class Source(db.Model):
    """
    Source Model: Stores academic papers retrieved via Semantic Scholar API.
    """
    __tablename__ = 'sources'

    id = db.Column(db.Integer, primary_key=True)
    paper_id = db.Column(db.Integer, db.ForeignKey('research_papers.id'), nullable=False)
    title = db.Column(db.String(500), nullable=False)
    authors = db.Column(db.Text, nullable=True)               # Comma-separated list of author names
    abstract = db.Column(db.Text, nullable=True)              # Summary of the reference paper
    url = db.Column(db.String(500), nullable=True)            # Link to the original paper
    publication_year = db.Column(db.Integer, nullable=True)   # Year of publication
